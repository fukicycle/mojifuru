/**
 * レア単語(濁点・半濁点をふくむ単語)の判定(純粋関数)。
 *
 * 降ってくる文字は辞書内のかな頻度で重み付けしているため(DEFAULT_KANA_WEIGHTS)、
 * 濁音・半濁音の文字は素の文字にくらべて桁違いに出にくい(例: 「ぺ」は「ん」の約170分の1)。
 * そのぶん濁点入りの単語は狙って作りにくいので、成立したときだけ特別な演出をして
 * 「たまたま作れた」を気持ちよさに変える。得点そのものには影響させない
 * (得点バランスはダウンコンボ込みで調整中のため、演出だけを足す)。
 */

/**
 * 濁点(U+3099)・半濁点(U+309A)の結合文字。
 * 「が」などの合成済みの文字もNFD正規化すれば「か」+結合濁点に分解されるため、
 * 濁音・半濁音の一覧を持たずに「ゔ」まで含めて判定できる。
 */
const COMBINING_VOICED_MARKS = /[゙゚]/;

/** 濁点・半濁点のついた文字をふくむ単語か */
export function isRareWord(word: string): boolean {
  return COMBINING_VOICED_MARKS.test(word.normalize('NFD'));
}
